export function getCardDesign(designName) {
  if (!designName) return CARD_DESIGNS.Bronze;
  if (CARD_DESIGNS[designName]) return CARD_DESIGNS[designName];

  // Aliases
  if (designName === 'Championship-style') return CARD_DESIGNS.Championship;
  if (designName === 'Icon-style' || designName === 'Hero-style') return CARD_DESIGNS.Elite;
  if (designName === 'TOTW-style') return CARD_DESIGNS.Special;

  return CARD_DESIGNS.Bronze;
}

